NAVY = '14213D'; TINT = 'F3F6FB'; HL = 'DCE9FA'
F = lambda **k: Font(name='Arial', **k)
thin = Side(style='thin', color='D9D8D2'); BOX = Border(left=thin, right=thin, top=thin, bottom=thin)
HEAD = dict(font=F(bold=True, color='FFFFFF', size=10), fill=PatternFill('solid', fgColor=NAVY))
INPUT = F(color='0000FF', size=10); CALC = F(color='000000', size=10); LINK = F(color='008000', size=10)
INT, PCT, PCT1 = '#,##0', '0.00%', '+0.0%;-0.0%;0.0%'

wb = Workbook()

def sheet(name, title, note=None):
    ws = wb.create_sheet(name)
    ws['A1'] = title; ws['A1'].font = F(bold=True, size=14, color=NAVY)
    if note: ws['A2'] = note; ws['A2'].font = F(italic=True, size=9, color='5F5E5A')
    ws.sheet_view.showGridLines = False
    return ws

def header(ws, r, cols, widths=None):
    for j, c in enumerate(cols, 1):
        cell = ws.cell(r, j, c); cell.font = HEAD['font']; cell.fill = HEAD['fill']; cell.border = BOX
        cell.alignment = Alignment(horizontal='center', vertical='center', wrap_text=True)
    if widths:
        for j, w in enumerate(widths, 1): ws.column_dimensions[get_column_letter(j)].width = w

def put(ws, r, c, v, font=CALC, fmt=None, hl=False, align=None):
    cell = ws.cell(r, c, v); cell.font = font; cell.border = BOX
    if fmt: cell.number_format = fmt
    if hl: cell.fill = PatternFill('solid', fgColor=HL)
    elif r % 2 == 0: cell.fill = PatternFill('solid', fgColor=TINT)
    if align: cell.alignment = Alignment(horizontal=align)
    return cell

COLS = {'FND': 'C', 'HND': 'D', 'LND': 'E', 'PDR': 'F'}
def look(key_cell, metric):
    return f"=INDEX('All runs'!${COLS[metric]}:${COLS[metric]},MATCH({key_cell},'All runs'!$B:$B,0))"

def bar(ws, title, cats, data_cols, first, last, anchor, ytitle='Rounds', w=18, h=8.5):
    ch = BarChart(); ch.type = 'col'; ch.grouping = 'clustered'; ch.title = title; ch.y_axis.title = ytitle
    ch.height = h; ch.width = w
    for col in data_cols:
        ch.add_data(Reference(ws, min_col=col, min_row=first - 1, max_row=last), titles_from_data=True)
    ch.set_categories(Reference(ws, min_col=cats, min_row=first, max_row=last))
    for s, c in zip(ch.series, ['2A78D6', 'EB6834', '1BAF7A']):
        s.graphicalProperties.solidFill = c; s.graphicalProperties.line.solidFill = c
    ws.add_chart(ch, anchor)

